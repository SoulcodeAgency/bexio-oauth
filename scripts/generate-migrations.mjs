// Embeds packages/bexio-oauth/sql/NNNN_*.sql into a TypeScript module, so
// `migrations()` needs no file system access at runtime and keeps working when
// an app's bundler (Next.js, esbuild, …) inlines the library. An optional
// NNNN_*.token-role.sql is embedded with its migration.
//
//   node scripts/generate-migrations.mjs           write the module
//   node scripts/generate-migrations.mjs --check   fail if it is out of date
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const SQL_DIR = new URL("../packages/bexio-oauth/sql/", import.meta.url);
const OUT = new URL(
  "../packages/bexio-oauth/src/migrations.generated.ts",
  import.meta.url,
);
const MIGRATION = /^\d{4}_[a-z0-9_]+\.sql$/;
const TOKEN_ROLE = /^(\d{4}_[a-z0-9_]+)\.token-role\.sql$/;

/** Escapes text for a template literal. */
const literal = (s) => s.replace(/\\|`|\$\{/g, (m) => "\\" + m);
const read = (name) =>
  readFileSync(new URL(name, SQL_DIR), "utf8").replace(/\r\n/g, "\n");

function render() {
  const files = readdirSync(SQL_DIR).sort();
  const migrations = files.filter((f) => MIGRATION.test(f));
  for (const f of files) {
    const match = TOKEN_ROLE.exec(f);
    if (
      !MIGRATION.test(f) &&
      !(match && migrations.includes(`${match[1]}.sql`))
    )
      throw new Error(
        `sql/${f}: not a migration or a migration's token-role part`,
      );
  }
  const entries = migrations.map((name) => {
    const tokenRole = name.replace(/\.sql$/, ".token-role.sql");
    return [
      "  {",
      `    number: ${Number.parseInt(name.slice(0, 4), 10)},`,
      `    name: ${JSON.stringify(name)},`,
      `    sql: \`${literal(read(name))}\`,`,
      ...(files.includes(tokenRole)
        ? [`    tokenRoleSql: \`${literal(read(tokenRole))}\`,`]
        : []),
      "  },",
    ].join("\n");
  });
  return [
    "// Generated by scripts/generate-migrations.mjs from sql/*.sql. Do not edit;",
    "// change the .sql file and run `npm run sql:generate`.",
    'import type { MigrationSource } from "./sql.js";',
    "",
    "export const MIGRATIONS: readonly MigrationSource[] = [",
    ...entries,
    "];",
    "",
  ].join("\n");
}

const expected = render();
if (process.argv.includes("--check")) {
  let actual = "";
  try {
    actual = readFileSync(OUT, "utf8").replace(/\r\n/g, "\n");
  } catch {
    // missing counts as out of date
  }
  if (actual !== expected) {
    console.error(
      "packages/bexio-oauth/src/migrations.generated.ts is out of date with sql/. Run `npm run sql:generate`.",
    );
    process.exit(1);
  }
} else {
  writeFileSync(OUT, expected);
}
