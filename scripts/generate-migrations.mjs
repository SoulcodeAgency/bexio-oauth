// Embeds packages/bexio-oauth/sql/NNNN_*.sql into a TypeScript module, so
// `migrations()` needs no file system access at runtime and keeps working when
// an app's bundler (Next.js, esbuild, …) inlines the library.
//
//   node scripts/generate-migrations.mjs           write the module
//   node scripts/generate-migrations.mjs --check   fail if it is out of date
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const SQL_DIR = new URL("../packages/bexio-oauth/sql/", import.meta.url);
const OUT = new URL(
  "../packages/bexio-oauth/src/migrations.generated.ts",
  import.meta.url,
);
const NAME = /^\d{4}_.+\.sql$/;

/** Escapes text for a template literal. */
const literal = (s) => s.replace(/\\|`|\$\{/g, (m) => "\\" + m);

function render() {
  const files = readdirSync(SQL_DIR)
    .filter((f) => NAME.test(f))
    .sort();
  const entries = files.map((name) => {
    const sql = readFileSync(new URL(name, SQL_DIR), "utf8").replace(
      /\r\n/g,
      "\n",
    );
    return [
      "  {",
      `    number: ${Number.parseInt(name.slice(0, 4), 10)},`,
      `    name: ${JSON.stringify(name)},`,
      `    sql: \`${literal(sql)}\`,`,
      "  },",
    ].join("\n");
  });
  return [
    "// Generated by scripts/generate-migrations.mjs from sql/*.sql. Do not edit;",
    "// change the .sql file and run `npm run sql:generate`.",
    'import type { Migration } from "./sql.js";',
    "",
    "export const MIGRATIONS: readonly Migration[] = [",
    ...entries,
    "];",
    "",
  ].join("\n");
}

const expected = render();
if (process.argv.includes("--check")) {
  let actual = "";
  try {
    actual = readFileSync(OUT, "utf8").replace(/\r\n/g, "\n");
  } catch {
    // missing counts as out of date
  }
  if (actual !== expected) {
    console.error(
      "packages/bexio-oauth/src/migrations.generated.ts is out of date with sql/. Run `npm run sql:generate`.",
    );
    process.exit(1);
  }
} else {
  writeFileSync(OUT, expected);
}
